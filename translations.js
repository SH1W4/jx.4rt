// Translation Manager
const TranslationManager = {
    currentLang: 'pt',
    
    init() {
        // Load saved language preference
        const savedLang = localStorage.getItem('jx4rt_language');
        if (savedLang && translations[savedLang]) {
            this.currentLang = savedLang;
        }
        
        this.applyLanguage(this.currentLang);
        this.setupToggle();
    },
    
    setupToggle() {
        const toggleBtn = document.getElementById('lang-toggle');
        if (toggleBtn) {
            toggleBtn.addEventListener('click', () => this.toggleLanguage());
        }
    },
    
    toggleLanguage() {
        this.currentLang = this.currentLang === 'pt' ? 'en' : 'pt';
        localStorage.setItem('jx4rt_language', this.currentLang);
        this.applyLanguage(this.currentLang);
    },
    
    applyLanguage(lang) {
        // Update HTML lang attribute
        document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en';
        
        // Update all elements with data-i18n attribute
        document.querySelectorAll('[data-i18n]').forEach(element => {
            const key = element.getAttribute('data-i18n');
            if (translations[lang][key]) {
                element.textContent = translations[lang][key];
            }
        });
        
        // Update select options with data-i18n attribute
        document.querySelectorAll('option[data-i18n]').forEach(option => {
            const key = option.getAttribute('data-i18n');
            if (translations[lang][key]) {
                option.textContent = translations[lang][key];
            }
        });
        
        // Update placeholder attributes
        document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
            const key = element.getAttribute('data-i18n-placeholder');
            if (translations[lang][key]) {
                element.placeholder = translations[lang][key];
            }
        });
        
        // Update toggle button text
        const toggleBtn = document.getElementById('lang-toggle');
        if (toggleBtn) {
            toggleBtn.textContent = lang === 'pt' ? 'EN' : 'PT';
        }
        
        // Update form step titles if they exist
        if (typeof FormHandler !== 'undefined' && FormHandler.stepTitle) {
            const stepTitles = {
                pt: [
                    "01 // IDENTIDADE & CONTATO",
                    "02 // DETALHES DO PROJETO",
                    "03 // INTENÇÃO",
                    "04 // LOGÍSTICA"
                ],
                en: [
                    "01 // IDENTITY & CONTACT",
                    "02 // PROJECT DETAILS",
                    "03 // INTENTION",
                    "04 // LOGISTICS"
                ]
            };
            FormHandler.titles = stepTitles[lang];
            // Update current step title if form is visible
            if (FormHandler.currentStep >= 1 && FormHandler.currentStep <= 4) {
                FormHandler.scrambleText(FormHandler.stepTitle, stepTitles[lang][FormHandler.currentStep - 1]);
            }
        }
    }
};

// Initialize on DOM ready
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => TranslationManager.init());
} else {
    TranslationManager.init();
}
